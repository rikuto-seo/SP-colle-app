# -----------------------------
# 正規化関数
# -----------------------------
def normalize_type(member: str, costume: str, photo_type: str) -> str:
    """
    photo_type を正規化する

    Parameters
    ----------
    member : str
        メンバー名（現状は未使用だが将来拡張用）
    costume : str
        衣装名
    photo_type : str
        元のタイプ（例: 01, ヨリ など）

    Returns
    -------
    str
        正規化されたタイプ
    """

    # 衣装単位でマッピング取得
    mapping = TYPE_NORMALIZATION_MAP.get(costume)

    if mapping:
        return mapping.get(photo_type, photo_type)

    # マッピング未定義ならそのまま返す
    return photo_type
