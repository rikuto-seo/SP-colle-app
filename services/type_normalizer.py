# ============================================================
# 正規化関数
# ============================================================

def normalize_type(member: str, costume: str, photo_type: str) -> str:
    """
    photo_type を正規化する。

    Parameters
    ----------
    member : str
        メンバー名
        現状は未使用だが将来拡張用。

    costume : str
        衣装名。

    photo_type : str
        元のタイプ。
        例:
            01
            ヨリ
            ヨリ（制服）
            チュウ（衣装）

    Returns
    -------
    str
        正規化されたタイプ。

    処理順
    --------
    1. 衣装固有の手動マッピング
    2. すでに正規化済みならそのまま
    3. photo_type 内に「ヨリ・チュウ・ヒキ・座り」が
       含まれていれば、その種類へ正規化
    4. 判定できなければ元の値を返す
    """

    # ========================================================
    # 1. 衣装単位で手動マッピング
    # ========================================================

    mapping = TYPE_NORMALIZATION_MAP.get(costume)

    if mapping and photo_type in mapping:
        normalized = mapping[photo_type]

        if normalized:
            return normalized

    # ========================================================
    # 2. すでに正規化済みの値
    # ========================================================

    if photo_type in NORMALIZED_TYPES:
        return photo_type

    # ========================================================
    # 3. photo_type 内に種類名が含まれている場合
    #
    # 例:
    #   ヨリ（制服） -> ヨリ
    #   チュウ（衣装） -> チュウ
    #   ヒキ（カンフー） -> ヒキ
    #   座り（白） -> 座り
    #
    # この処理があるため、これらを
    # TYPE_NORMALIZATION_MAP に個別登録する必要はない。
    # ========================================================

    for normalized_type in NORMALIZED_TYPES:
        if normalized_type in photo_type:
            return normalized_type

    # ========================================================
    # 4. 判定できない値はそのまま返す
    # ========================================================

    return photo_type