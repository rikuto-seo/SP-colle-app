"""
photo_type 正規化ユーティリティ

目的:
- 衣装ごとに異なる photo_type 表現（例: 01,02,03）を
  統一的な分類（ヨリ/チュウ/ヒキなど）へ変換する
- 統計処理・コンプ判定の一貫性を保つ
- photo_type の表示・集計順を統一する

種類の正式な順序:
    ヨリ → チュウ → ヒキ → 座り

注意:
- 数字などの衣装固有タイプは TYPE_NORMALIZATION_MAP に手動定義する
- 「ヨリ（制服）」「チュウ（衣装）」など、photo_type 自体に
  正規化後の種類名が含まれるものはマッピング不要
"""


from typing import Dict, Iterable, List


# ============================================================
# 正規化後の種類
# ============================================================

NORMALIZED_TYPES = ("ヨリ", "チュウ", "ヒキ", "座り")


# ============================================================
# 種類の表示・集計順
# ============================================================

TYPE_ORDER = {
    "ヨリ": 1,
    "チュウ": 2,
    "ヒキ": 3,
    "座り": 4,
}


def get_type_order(photo_type: str) -> int:
    """
    photo_type の表示・集計順を返す。

    正規化済みの4種類:
        ヨリ   -> 1
        チュウ -> 2
        ヒキ   -> 3
        座り   -> 4

    未知の値は最後に配置する。
    """
    return TYPE_ORDER.get(photo_type, 999)


def sort_types(types: Iterable[str]) -> List[str]:
    """
    photo_type の一覧を正式な種類順に並べる。

    順序:
        ヨリ → チュウ → ヒキ → 座り

    未知の値は最後に配置する。
    """
    return sorted(types, key=get_type_order)


